const RECENT_KEY = "cirvo:recent-emoji";
const RECENT_CAP = 24;

function loadRecent(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    if (!raw) return [];
    const arr = JSON.parse(raw) as unknown;
    return Array.isArray(arr) ? arr.filter((x): x is string => typeof x === "string").slice(0, RECENT_CAP) : [];
  } catch {
    return [];
  }
}

function pushRecent(emoji: string): void {
  try {
    const next = [emoji, ...loadRecent().filter((e) => e !== emoji)].slice(0, RECENT_CAP);
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    /* localStorage недоступен — recently просто не работает */
  }
}

let containerEl: HTMLDivElement | null = null;
let outsideHandler: ((ev: MouseEvent) => void) | null = null;
let keyHandler: ((ev: KeyboardEvent) => void) | null = null;

function ensureContainer(): HTMLDivElement {
  if (containerEl && document.body.contains(containerEl)) return containerEl;
  containerEl = document.createElement("div");
  containerEl.id = "cirvo-emoji-picker";
  document.body.appendChild(containerEl);
  return containerEl;
}

export function closeEmojiPicker(): void {
  if (outsideHandler) {
    document.removeEventListener("mousedown", outsideHandler, true);
    outsideHandler = null;
  }
  if (keyHandler) {
    window.removeEventListener("keydown", keyHandler, true);
    keyHandler = null;
  }
  containerEl?.replaceChildren();
}

export function isEmojiPickerOpen(): boolean {
  return !!containerEl && containerEl.childElementCount > 0;
}

export function openEmojiPicker(opts: EmojiPickerOpts): void {
  // Повторный клик по той же кнопке — toggle.
  if (isEmojiPickerOpen()) {
    closeEmojiPicker();
    return;
  }
  const root = ensureContainer();
  root.innerHTML = `
    <div class="ep-card" role="dialog" aria-label="Выбор эмодзи">
      <input class="ep-search" type="text" placeholder="Поиск эмодзи…" />
      <div class="ep-body"></div>
    </div>
  `;
  const card = root.querySelector<HTMLDivElement>(".ep-card")!;
  const search = root.querySelector<HTMLInputElement>(".ep-search")!;
  const body = root.querySelector<HTMLDivElement>(".ep-body")!;

  // Позиционирование: над якорем, клампим в окно.
  const rect = opts.anchor.getBoundingClientRect();
  const cardW = 332;
  const cardH = 384;
  let left = Math.min(Math.max(8, rect.left), window.innerWidth - cardW - 8);
  let top = rect.top - cardH - 8;
  if (top < 8) top = Math.min(rect.bottom + 8, window.innerHeight - cardH - 8);
  card.style.left = `${left}px`;
  card.style.top = `${top}px`;

  const renderSections = (query: string) => {
    const q = query.trim().toLowerCase();
    const parts: string[] = [];
    const renderGrid = (items: EmojiEntry[]) =>
      `<div class="ep-grid">${items
        .map(([e]) => `<button class="ep-emoji" data-emoji="${e}" type="button">${e}</button>`)
        .join("")}</div>`;
    if (!q) {
      const recent = loadRecent();
      if (recent.length > 0) {
        parts.push(`<div class="ep-section-title">Недавние</div>`);
        parts.push(renderGrid(recent.map((e) => [e, ""] as EmojiEntry)));
      }
      for (const cat of CATEGORIES) {
        parts.push(`<div class="ep-section-title">${cat.label}</div>`);
        parts.push(renderGrid(cat.items));
      }
    } else {
      const hits: EmojiEntry[] = [];
      for (const cat of CATEGORIES) {
        for (const entry of cat.items) {
          if (entry[1].toLowerCase().includes(q)) hits.push(entry);
          if (hits.length >= 64) break;
        }
        if (hits.length >= 64) break;
      }
      parts.push(
        hits.length > 0
          ? renderGrid(hits)
          : `<div class="ep-empty">Ничего не найдено</div>`
      );
    }
    body.innerHTML = parts.join("");
  };
  renderSections("");

  search.addEventListener("input", () => renderSections(search.value));
  // Фокус в поиск сразу — Discord-pattern.
  requestAnimationFrame(() => search.focus());

  body.addEventListener("click", (ev) => {
    const btn = (ev.target as HTMLElement).closest<HTMLButtonElement>(".ep-emoji");
    if (!btn?.dataset.emoji) return;
    pushRecent(btn.dataset.emoji);
    opts.onPick(btn.dataset.emoji);
    if (opts.closeOnPick !== false) closeEmojiPicker();
  });

  outsideHandler = (ev) => {
    const t = ev.target as HTMLElement;
    if (!card.contains(t) && t !== opts.anchor && !opts.anchor.contains(t)) {
      closeEmojiPicker();
    }
  };
  document.addEventListener("mousedown", outsideHandler, true);

  keyHandler = (ev) => {
    if (ev.key === "Escape") {
      ev.stopPropagation();
      closeEmojiPicker();
    }
  };
  window.addEventListener("keydown", keyHandler, true);
}
